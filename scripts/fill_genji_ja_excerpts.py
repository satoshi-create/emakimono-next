def main() -> None:
    data = json.loads(PATH.read_text(encoding="utf-8"))
    assert len(KOBUN) == 54, len(KOBUN)

    for e in data:
        ch = str(e["chapter_en"])
        if ch not in KOBUN:
            raise SystemExit(f"missing kobun for {ch}")

        # Preserve non-empty pilot kobun/gendaibun if already set
        existing_kobun = (e.get("kobun") or "").strip()
        existing_gendai = (e.get("gendaibun") or "").strip()

        e["kobun"] = existing_kobun or KOBUN[ch]
        if ch in GENDAIBUN_OVERRIDE and existing_gendai:
            e["gendaibun"] = existing_gendai
        elif ch in GENDAIBUN_OVERRIDE:
            e["gendaibun"] = GENDAIBUN_OVERRIDE[ch]
        else:
            e["gendaibun"] = existing_gendai or clip_gendaibun(e.get("summary") or "")

        e.pop("desc", None)
        e.pop("descen", None)

    PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(
        "kobun",
        sum(1 for e in data if (e.get("kobun") or "").strip()),
        "gendaibun",
        sum(1 for e in data if (e.get("gendaibun") or "").strip()),
    )
    # quick sample
    for i in (1, 11, 53):
        e = data[i]
        print(
            f"ch{e['chapter_en']} kobun={len(e['kobun'])} gendaibun={len(e['gendaibun'])} "
            f"head={e['kobun'][:28]}"
        )


if __name__ == "__main__":
    main()

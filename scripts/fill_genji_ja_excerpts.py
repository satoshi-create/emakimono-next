def clip_gendaibun(summary: str, max_len: int = 160) -> str:
    s = (summary or "").strip()
    if not s:
        return ""
    if len(s) <= max_len:
        return s if s.endswith(("。", "……", "…")) else s + "……"
    cut = s[:max_len]
    idx = cut.rfind("。")
    if idx >= 60:
        return cut[: idx + 1] + "……"
    return cut.rstrip("、") + "……"


